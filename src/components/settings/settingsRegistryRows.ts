import type { SettingsRowAvailability, SettingsSectionId } from "./settingsRegistry";

interface SettingsRowRecord {
  readonly id: string;
  readonly section: SettingsSectionId;
  readonly title: string;
  readonly description: string | null;
  readonly keywords: ReadonlyArray<string>;
  readonly availability: SettingsRowAvailability;
}

function row<Id extends string>(
  id: Id,
  section: SettingsSectionId,
  title: string,
  description: string | null,
  keywords: ReadonlyArray<string>,
  availability: SettingsRowAvailability = "always",
): SettingsRowRecord & { readonly id: Id } {
  return { id, section, title, description, keywords, availability };
}

