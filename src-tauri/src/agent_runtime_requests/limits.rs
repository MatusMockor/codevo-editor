use crate::agent_questions::approvals::{
    MAX_AGENT_APPROVAL_DETAIL_BYTES, MAX_AGENT_APPROVAL_FACTS, MAX_AGENT_APPROVAL_FACT_LABEL_BYTES,
    MAX_AGENT_APPROVAL_FACT_VALUE_BYTES, MAX_AGENT_APPROVAL_TITLE_BYTES,
};
use crate::agent_questions::{
    MAX_AGENT_QUESTIONS_PER_REQUEST, MAX_AGENT_QUESTION_ANSWER_TEXT_BYTES,
    MAX_AGENT_QUESTION_HEADER_BYTES, MAX_AGENT_QUESTION_ID_BYTES, MAX_AGENT_QUESTION_OPTIONS,
    MAX_AGENT_QUESTION_OPTION_DESCRIPTION_BYTES, MAX_AGENT_QUESTION_OPTION_LABEL_BYTES,
    MAX_AGENT_QUESTION_PROMPT_BYTES,
};

pub const MAX_JSON_BYTES_PER_TEXT_BYTE: usize = 6;
pub const JSON_OBJECT_ALLOWANCE_BYTES: usize = 256;

const fn text(bytes: usize) -> usize {
    bytes * MAX_JSON_BYTES_PER_TEXT_BYTE
}

const fn largest(left: usize, right: usize) -> usize {
    if left > right {
        return left;
    }
    right
}

const LISTED_IDENTIFIER_BYTES: usize = MAX_AGENT_QUESTION_ID_BYTES + 3;

const ANSWER_BYTES: usize = JSON_OBJECT_ALLOWANCE_BYTES
    + MAX_AGENT_QUESTION_ID_BYTES
    + MAX_AGENT_QUESTION_OPTIONS * LISTED_IDENTIFIER_BYTES
    + text(MAX_AGENT_QUESTION_ANSWER_TEXT_BYTES);

pub const MAX_REQUEST_OUTCOME_BYTES: usize =
    JSON_OBJECT_ALLOWANCE_BYTES + MAX_AGENT_QUESTIONS_PER_REQUEST * ANSWER_BYTES;

const OPTION_BYTES: usize = JSON_OBJECT_ALLOWANCE_BYTES
    + MAX_AGENT_QUESTION_ID_BYTES
    + text(MAX_AGENT_QUESTION_OPTION_LABEL_BYTES)
    + text(MAX_AGENT_QUESTION_OPTION_DESCRIPTION_BYTES);

const QUESTION_BYTES: usize = JSON_OBJECT_ALLOWANCE_BYTES
    + MAX_AGENT_QUESTION_ID_BYTES
    + text(MAX_AGENT_QUESTION_HEADER_BYTES)
    + text(MAX_AGENT_QUESTION_PROMPT_BYTES)
    + MAX_AGENT_QUESTION_OPTIONS * OPTION_BYTES;

pub const MAX_QUESTION_BODY_BYTES: usize =
    2 * JSON_OBJECT_ALLOWANCE_BYTES + MAX_AGENT_QUESTIONS_PER_REQUEST * QUESTION_BYTES;

const FACT_BYTES: usize = JSON_OBJECT_ALLOWANCE_BYTES
    + text(MAX_AGENT_APPROVAL_FACT_LABEL_BYTES)
    + text(MAX_AGENT_APPROVAL_FACT_VALUE_BYTES);

pub const MAX_APPROVAL_BODY_BYTES: usize = 3 * JSON_OBJECT_ALLOWANCE_BYTES
    + text(MAX_AGENT_APPROVAL_TITLE_BYTES)
    + text(MAX_AGENT_APPROVAL_DETAIL_BYTES)
    + MAX_AGENT_APPROVAL_FACTS * FACT_BYTES;

pub const MAX_REQUEST_BODY_BYTES: usize = largest(MAX_QUESTION_BODY_BYTES, MAX_APPROVAL_BODY_BYTES);
